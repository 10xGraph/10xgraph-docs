import type { APIRoute } from 'astro';

// Search and AI answer engines are allowed on purpose: being cited by ChatGPT, Claude,
// Perplexity and Google AI features requires that their crawlers can read the site.
export const GET: APIRoute = ({ site }) => {
  const sitemap = new URL('sitemap-index.xml', site).toString();
  const body = [
    'User-agent: *',
    'Allow: /',
    '',
    '# Search engines (also feed Google AI Overviews and Bing Copilot)',
    'User-agent: Googlebot',
    'User-agent: Bingbot',
    'User-agent: Applebot',
    'User-agent: DuckDuckBot',
    'Allow: /',
    '',
    '# AI search and user-triggered fetch (citations in answers)',
    'User-agent: OAI-SearchBot',
    'User-agent: ChatGPT-User',
    'User-agent: Claude-SearchBot',
    'User-agent: Claude-User',
    'User-agent: PerplexityBot',
    'User-agent: Perplexity-User',
    'User-agent: DuckAssistBot',
    'User-agent: MistralAI-User',
    'User-agent: MistralAI-Index',
    'User-agent: meta-externalfetcher',
    'User-agent: meta-webindexer',
    'User-agent: YouBot',
    'User-agent: Amazonbot',
    'User-agent: Amzn-SearchBot',
    'User-agent: Amzn-User',
    'Allow: /',
    '',
    '# AI training (separate group so it can be blocked later without affecting search)',
    'User-agent: GPTBot',
    'User-agent: ClaudeBot',
    'User-agent: Google-Extended',
    'User-agent: Applebot-Extended',
    'User-agent: meta-externalagent',
    'User-agent: MistralAI-Training',
    'User-agent: CCBot',
    'Allow: /',
    '',
    `Sitemap: ${sitemap}`,
    '',
  ].join('\n');
  return new Response(body, { headers: { 'Content-Type': 'text/plain; charset=utf-8' } });
};
